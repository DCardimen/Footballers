// v195 B THE MASCOT, V2 — every crest's own colours, read off its pixels.
//
// The owner: "Colors exact to mascot logos." The 90 v44 crests are painted raster art (public/rib_logos_v44.png, a
// 10x9 grid of 128px cells in LOGO_DB order), so there is no colour table to copy: this script reads each crest's
// palette off the sheet and writes it into src/35-mascots.js as `LOGO_PAL_V195B` (between the generated markers —
// edit this script, not the block).
//
//   1. decode the PNG (pure Node: zlib + the five PNG row filters; no canvas, no browser)
//   2. per cell: the opaque pixels (alpha >= ALPHA), ERODED by RIM px — every crest wears a light keyline and a dark
//      outline round its silhouette, which is the sticker's border, not the creature's colour
//   3. k-means in CIE Lab (K clusters, seeded deterministically by farthest point from the commonest 5-bit bins),
//      clusters closer than MERGE ΔE merged, anything under MIN_SHARE of the crest dropped
//   4. each cluster is named by a colour the crest really contains: the commonest 5-bit bin inside the cluster, and
//      the mean of the actual pixels in that bin (so every hex is a colour you can find on the crest)
//   5. the line per crest: "rrggbb:share,…" by share (percent of the crest's interior), commonest first, then "|rrggbb"
//      the KEYLINE — the commonest light colour of the rim step 2 cut away (the wolf's cyan glow, most crests' cream)
//
//   node scripts/build-mascot-palettes.mjs          (rewrites the block; --print only prints it)
import fs from 'node:fs'
import zlib from 'node:zlib'

const SHEET = 'public/rib_logos_v44.png', TARGET = 'src/35-mascots.js'
const COLS = 10, ROWS = 9, CELL = 128
const ALPHA = 200, RIM = 5, K = 8, MERGE = 9, MIN_SHARE = 0.018, KEEP = 8
const BEGIN = '/* <generated by scripts/build-mascot-palettes.mjs: LOGO_PAL_V195B> */', END = '/* </generated LOGO_PAL_V195B> */'

function decodePNG (buf) {
  let p = 8, W = 0, H = 0, bitDepth = 0, colorType = 0
  const idat = []
  while (p < buf.length) {
    const len = buf.readUInt32BE(p), type = buf.toString('ascii', p + 4, p + 8), data = buf.subarray(p + 8, p + 8 + len)
    if (type === 'IHDR') { W = data.readUInt32BE(0); H = data.readUInt32BE(4); bitDepth = data[8]; colorType = data[9] }
    else if (type === 'IDAT') idat.push(data)
    else if (type === 'IEND') break
    p += 12 + len
  }
  if (bitDepth !== 8 || colorType !== 6) throw new Error('expected 8-bit RGBA, got depth ' + bitDepth + ' type ' + colorType)
  const raw = zlib.inflateSync(Buffer.concat(idat)), bpp = 4, stride = W * bpp, out = Buffer.alloc(W * H * bpp)
  for (let y = 0; y < H; y++) {
    const f = raw[y * (stride + 1)], src = y * (stride + 1) + 1, dst = y * stride
    for (let x = 0; x < stride; x++) {
      const a = x >= bpp ? out[dst + x - bpp] : 0, b = y ? out[dst - stride + x] : 0, c = x >= bpp && y ? out[dst - stride + x - bpp] : 0
      let v = raw[src + x]
      if (f === 1) v += a; else if (f === 2) v += b; else if (f === 3) v += (a + b) >> 1
      else if (f === 4) { const pp = a + b - c, pa = Math.abs(pp - a), pb = Math.abs(pp - b), pc = Math.abs(pp - c); v += pa <= pb && pa <= pc ? a : pb <= pc ? b : c }
      out[dst + x] = v & 255
    }
  }
  return { W, H, px: out }
}
// sRGB → CIE Lab (D65)
function lab (r, g, b) {
  const l = (v) => { v /= 255; return v <= 0.04045 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4) }
  const R = l(r), G = l(g), B = l(b)
  const X = (R * 0.4124 + G * 0.3576 + B * 0.1805) / 0.95047, Y = R * 0.2126 + G * 0.7152 + B * 0.0722, Z = (R * 0.0193 + G * 0.1192 + B * 0.9505) / 1.08883
  const f = (t) => t > 0.008856 ? Math.cbrt(t) : 7.787 * t + 16 / 116
  return [116 * f(Y) - 16, 500 * (f(X) - f(Y)), 200 * (f(Y) - f(Z))]
}
const dE = (a, b) => Math.hypot(a[0] - b[0], a[1] - b[1], a[2] - b[2])
const hex = (r, g, b) => [r, g, b].map((v) => Math.round(v).toString(16).padStart(2, '0')).join('')

function paletteOf (img, cx, cy) {
  const { W, px } = img, x0 = cx * CELL, y0 = cy * CELL
  // the mask and its erosion (a chessboard distance to the nearest see-through pixel)
  const N = CELL * CELL, solid = new Uint8Array(N)
  for (let y = 0; y < CELL; y++) for (let x = 0; x < CELL; x++) solid[y * CELL + x] = px[((y0 + y) * W + x0 + x) * 4 + 3] >= ALPHA ? 1 : 0
  let inner = solid
  for (let r = 0; r < RIM; r++) {
    const nx = new Uint8Array(N)
    for (let y = 1; y < CELL - 1; y++) for (let x = 1; x < CELL - 1; x++) {
      const i = y * CELL + x
      nx[i] = inner[i] && inner[i - 1] && inner[i + 1] && inner[i - CELL] && inner[i + CELL] ? 1 : 0
    }
    inner = nx
  }
  // the commonest 5-bit bins (the seeds) and every interior pixel
  const pts = [], bins = new Map()
  for (let i = 0; i < N; i++) {
    if (!inner[i]) continue
    const y = Math.floor(i / CELL), x = i % CELL, o = ((y0 + y) * W + x0 + x) * 4, r = px[o], g = px[o + 1], b = px[o + 2]
    const key = ((r >> 3) << 10) | ((g >> 3) << 5) | (b >> 3)
    pts.push({ r, g, b, L: lab(r, g, b), key })
    const e = bins.get(key) || { n: 0, r: 0, g: 0, b: 0 }; e.n++; e.r += r; e.g += g; e.b += b; bins.set(key, e)
  }
  if (!pts.length) return { pal: [], rim: null }
  const top = [...bins.entries()].sort((a, b) => b[1].n - a[1].n || a[0] - b[0]).slice(0, 64).map(([k, e]) => ({ k, L: lab(e.r / e.n, e.g / e.n, e.b / e.n), n: e.n }))
  const seeds = [top[0].L]
  while (seeds.length < K && seeds.length < top.length) {
    let best = null, bd = -1
    for (const t of top) { const d = Math.min(...seeds.map((s) => dE(s, t.L))) * Math.sqrt(t.n); if (d > bd) { bd = d; best = t } }
    if (!best || bd <= 0) break
    seeds.push(best.L)
  }
  let C = seeds.map((s) => s.slice()), asg = new Int16Array(pts.length)
  for (let it = 0; it < 14; it++) {
    const acc = C.map(() => [0, 0, 0, 0])
    pts.forEach((p, i) => { let b = 0, bd = 1e9; C.forEach((c, j) => { const d = dE(c, p.L); if (d < bd) { bd = d; b = j } }); asg[i] = b; const a = acc[b]; a[0] += p.L[0]; a[1] += p.L[1]; a[2] += p.L[2]; a[3]++ })
    C = C.map((c, j) => acc[j][3] ? [acc[j][0] / acc[j][3], acc[j][1] / acc[j][3], acc[j][2] / acc[j][3]] : c)
  }
  // merge the near twins
  let groups = C.map((c, j) => ({ c, members: [j] }))
  for (let again = true; again;) {
    again = false
    for (let a = 0; a < groups.length && !again; a++) for (let b = a + 1; b < groups.length && !again; b++) {
      if (dE(groups[a].c, groups[b].c) < MERGE) { groups[a].members.push(...groups[b].members); groups.splice(b, 1); again = true }
    }
  }
  const out = []
  for (const g of groups) {
    const mine = new Set(g.members), local = new Map(); let n = 0
    pts.forEach((p, i) => { if (!mine.has(asg[i])) return; n++; const e = local.get(p.key) || { n: 0, r: 0, g: 0, b: 0 }; e.n++; e.r += p.r; e.g += p.g; e.b += p.b; local.set(p.key, e) })
    if (!n) continue
    const [, m] = [...local.entries()].sort((a, b) => b[1].n - a[1].n || a[0] - b[0])[0]
    out.push({ hex: hex(m.r / m.n, m.g / m.n, m.b / m.n), share: n / pts.length })
  }
  // two clusters can be named by near-identical colours: fold them together
  out.sort((a, b) => b.share - a.share)
  const fold = []
  for (const c of out) { const L = lab(...rgbOf(c.hex)), t = fold.find((f) => dE(f.L, L) < MERGE); if (t) t.share += c.share; else fold.push(Object.assign({ L }, c)) }
  const pal = fold.filter((c) => c.share >= MIN_SHARE).slice(0, KEEP)
  // the KEYLINE: the crest's rim (solid, but not the interior), its commonest colour that is not the dark outline —
  // the wolf's cyan, the boar's red, the eagle's gold, most crests' cream
  const rim = new Map()
  for (let i = 0; i < N; i++) {
    if (!solid[i] || inner[i]) continue
    const y = Math.floor(i / CELL), x = i % CELL, o = ((y0 + y) * W + x0 + x) * 4, r = px[o], g = px[o + 1], b = px[o + 2]
    if (lab(r, g, b)[0] < 30) continue
    const key = ((r >> 3) << 10) | ((g >> 3) << 5) | (b >> 3), e = rim.get(key) || { n: 0, r: 0, g: 0, b: 0 }; e.n++; e.r += r; e.g += g; e.b += b; rim.set(key, e)
  }
  const rt = [...rim.entries()].sort((a, b) => b[1].n - a[1].n || a[0] - b[0])[0]
  return { pal, rim: rt ? hex(rt[1].r / rt[1].n, rt[1].g / rt[1].n, rt[1].b / rt[1].n) : null }
}
const rgbOf = (h) => [parseInt(h.slice(0, 2), 16), parseInt(h.slice(2, 4), 16), parseInt(h.slice(4, 6), 16)]

const img = decodePNG(fs.readFileSync(SHEET))
const lines = []
for (let i = 0; i < COLS * ROWS; i++) {
  const { pal, rim } = paletteOf(img, i % COLS, Math.floor(i / COLS))
  lines.push(JSON.stringify(pal.map((c) => c.hex + ':' + Math.round(c.share * 100)).join(',') + (rim ? '|' + rim : '')))
}
const block = BEGIN + '\n  /* the 90 crests in LOGO_DB order: "rrggbb:share%,…|keyline" read off public/rib_logos_v44.png */\n  const LOGO_PAL_V195B = [\n' +
  lines.map((l, i) => '    ' + l + (i < lines.length - 1 ? ',' : '')).reduce((acc, l, i) => { if (i % 5 === 0) acc.push([]); acc[acc.length - 1].push(l.trim()); return acc }, []).map((row) => '    ' + row.join(' ')).join('\n') +
  '\n  ];\n  ' + END
if (process.argv.includes('--print')) { console.log(block); process.exit(0) }
const src = fs.readFileSync(TARGET, 'utf8'), a = src.indexOf(BEGIN), b = src.indexOf(END)
if (a < 0 || b < 0) { console.error('markers not found in ' + TARGET + ' — add the two marker lines where the block goes'); process.exit(1) }
fs.writeFileSync(TARGET, src.slice(0, a) + block + src.slice(b + END.length))
console.log('wrote ' + lines.length + ' crest palettes into ' + TARGET)
